/* ---------------------------------------------------------------
 * 16. Stock single-product gallery — wc_get_gallery_image_html builds
 *     a <div class="woocommerce-product-gallery__image"><a><img></a>
 *     </div>. The img is rewritten to WebP by the buffer pass; the
 *     outer <div> + <a> get a class boost via the filter so the
 *     flexslider / zoom / photoswipe JS (which targets those classes)
 *     keeps working AND the markup looks themed.
 * ------------------------------------------------------------- */
function blogpro_wcom_gallery_image_html( $html, $attachment_id = 0 ) {
    // WC's templates fire this filter with 2 args only; the main image
    // is identifiable by the .wp-post-image class on its <img>.
    if ( false !== strpos( $html, 'wp-post-image' ) ) {
        $html = str_replace(
            'class="woocommerce-product-gallery__image"',
            'class="woocommerce-product-gallery__image block overflow-hidden rounded-2xl bg-white"',
            $html
        );
        $html = str_replace( 'class="wp-post-image"', 'class="wp-post-image w-full h-auto object-cover"', $html );
    } else {
        $html = str_replace(
            'class="woocommerce-product-gallery__image"',
            'class="woocommerce-product-gallery__image rounded-lg overflow-hidden border border-gray-100"',
            $html
        );
    }
    return $html;
}
add_filter( 'woocommerce_single_product_image_thumbnail_html', 'blogpro_wcom_gallery_image_html', 10, 2 );

