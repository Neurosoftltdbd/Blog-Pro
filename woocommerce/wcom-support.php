/**
 * WooCommerce Support
 * Loads only when WooCommerce plugin is active.
 *
 * Template strategy
 * -----------------
 * - Templates that need bespoke Tailwind markup (e.g. notices, the review
 *   order table, the single-product image gallery) get a real file in
 *   /woocommerce/ — those go through the normal WC template loader.
 * - Stock markup we still inherit (form fields, quantity inputs, payment
 *   methods, the checkout loop start, the rating stars) gets Tailwind
 *   classes injected via the filters below, so the look stays consistent
 *   with the rest of the theme without overriding every template.
 *
 * Images
 * ------
 * The media-optimize helper blogpro_responsive_img() is the one source of
 * truth for rendering <img> in the theme — it emits WebP via the
 * /blogpro-img/ resizer with a 320/480/768/1024/1280/1600 srcset. The new
 * templates call it directly. For images that still come from stock WC
 * markup (e.g. the gallery main image, the product thumbnail <img>
 * generated by wc_get_gallery_image_html) the whole-page
 * blogpro_responsive_buffer_images() pass in media-optimize rewrites every
 * <img> to the resizer URL.
 */

